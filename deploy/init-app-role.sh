#!/bin/sh
set -eu
: "${MATMS_APP_DB_PASSWORD:?Application database password is required}"
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=ON_ERROR_STOP=1 --set=app_password="$MATMS_APP_DB_PASSWORD" <<'SQL'
CREATE ROLE matms_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'app_password';
GRANT CONNECT ON DATABASE matms TO matms_app;
GRANT USAGE ON SCHEMA public TO matms_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO matms_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO matms_app;
SQL
