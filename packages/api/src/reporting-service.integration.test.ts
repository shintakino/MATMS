import { afterAll, expect, test } from "bun:test";
import { eq, inArray } from "drizzle-orm";

import { provisionAccount } from "@matms/auth/provisioning";
import { createDb } from "@matms/db";
import { accessGrants, boxes, categories, documents, folders, shelfLocations } from "@matms/db/schema/archive";
import { auditLogs } from "@matms/db/schema/audit";
import { user } from "@matms/db/schema/auth";
import { userProfiles } from "@matms/db/schema/identity";

import { createBox, createCategory, createDocument, createFolder, createLocation, grantAccess, revokeAccess, listFolderChoices } from "./archive-service";
import { previewAccess, auditFilterChoices } from "./admin-service";
import { dashboard, exportReport, queryReport, reportKinds } from "./reporting-service";

const databaseUrl = process.env.TEST_DATABASE_URL;
if (!databaseUrl || !new URL(databaseUrl).pathname.endsWith("_test")) throw new Error("TEST_DATABASE_URL must be an isolated _test database.");
const db = createDb({ DATABASE_URL: databaseUrl });
const suffix = crypto.randomUUID();
const correlationId = crypto.randomUUID();
const users: string[] = [];
const fixture = { category: "", location: "", box: "", hiddenBox: "", folder: "", hiddenFolder: "", doc: "", hiddenDoc: "" };

afterAll(async () => {
  if (fixture.hiddenBox) await db.delete(accessGrants).where(eq(accessGrants.boxId, fixture.hiddenBox));
  if (fixture.hiddenFolder) await db.delete(accessGrants).where(eq(accessGrants.folderId, fixture.hiddenFolder));
  const documentIds = [fixture.doc, fixture.hiddenDoc].filter(Boolean);
  const folderIds = [fixture.folder, fixture.hiddenFolder].filter(Boolean);
  const boxIds = [fixture.box, fixture.hiddenBox].filter(Boolean);
  if (documentIds.length) await db.delete(documents).where(inArray(documents.id, documentIds));
  if (folderIds.length) await db.delete(folders).where(inArray(folders.id, folderIds));
  if (boxIds.length) await db.delete(boxes).where(inArray(boxes.id, boxIds));
  if (fixture.location) await db.delete(shelfLocations).where(eq(shelfLocations.id, fixture.location));
  if (fixture.category) await db.delete(categories).where(eq(categories.id, fixture.category));
  await db.delete(auditLogs).where(eq(auditLogs.correlationId, correlationId));
  for (const id of users) { await db.delete(userProfiles).where(eq(userProfiles.userId, id)); await db.delete(user).where(eq(user.id, id)); }
});

test("search, dashboard, and CSV use the same restricted scope and neutralize spreadsheet formulas", async () => {
  const adminAccount = await provisionAccount(db, { name: "Report admin", email: `report-admin-${suffix}@example.test`, password: "report fixture password", role: "admin", actorId: null, correlationId, mustChangePassword: false });
  users.push(adminAccount.id);
  const staffAccount = await provisionAccount(db, { name: "Report staff", email: `report-staff-${suffix}@example.test`, password: "report fixture password", role: "staff", actorId: adminAccount.id, correlationId, mustChangePassword: false });
  users.push(staffAccount.id);
  const admin = { id: adminAccount.id, role: "admin" as const };
  const staff = { id: staffAccount.id, role: "staff" as const };
  const viewer = { id: staffAccount.id, role: "viewer" as const };
  const code = suffix.slice(0, 8);
  fixture.category = (await createCategory(db, admin, { code: `RC-${code}`, name: "Reports fixture", correlationId })).id;
  fixture.location = (await createLocation(db, admin, { code: `RL-${code}`, room: "Room", shelf: "A", rack: "1", label: "Room A", correlationId })).id;
  fixture.box = (await createBox(db, admin, { code: `RB-${code}`, categoryId: fixture.category, shelfLocationId: fixture.location, confidentiality: "internal", correlationId })).id;
  fixture.hiddenBox = (await createBox(db, admin, { code: `RX-${code}`, categoryId: fixture.category, shelfLocationId: fixture.location, confidentiality: "restricted", correlationId })).id;
  fixture.folder = (await createFolder(db, admin, { boxId: fixture.box, code: `RF-${code}`, name: "Public fixture", color: "blue", isTemplateFolder: true, confidentiality: "internal", correlationId })).id;
  fixture.hiddenFolder = (await createFolder(db, admin, { boxId: fixture.hiddenBox, code: `RH-${code}`, name: "Hidden fixture", color: "red", confidentiality: "internal", correlationId })).id;
  fixture.doc = (await createDocument(db, admin, { folderId: fixture.folder, code: `RD-${code}`, title: '=SUM(1,1), "quoted"\nsecond line', confidentiality: "internal", correlationId })).id;
  fixture.hiddenDoc = (await createDocument(db, admin, { folderId: fixture.hiddenFolder, code: `RS-${code}`, title: `Hidden secret ${code}`, confidentiality: "internal", correlationId })).id;

  const folderChoices = await listFolderChoices(db, staff);
  expect(folderChoices.find((choice) => choice.id === fixture.folder)).toMatchObject({ isTemplateFolder: true, locationLabel: "Room A" });
  expect(folderChoices.some((choice) => choice.id === fixture.hiddenFolder)).toBe(false);
  await expect(previewAccess(db, staff, { userId: staff.id, targetType: "document", targetId: fixture.hiddenDoc })).rejects.toThrow();
  await expect(auditFilterChoices(db, staff)).rejects.toThrow();
  const beforeGrant = await previewAccess(db, admin, { userId: staff.id, targetType: "document", targetId: fixture.hiddenDoc });
  expect(beforeGrant.path.map((level) => level.type)).toEqual(["box", "folder", "document"]);
  expect(beforeGrant.missing.map((level) => level.id)).toEqual([fixture.hiddenBox]);
  expect(beforeGrant.effectiveNow).toBe(false);
  expect(beforeGrant.effectiveAfterTargetGrant).toBe(false);
  expect((await previewAccess(db, admin, { userId: admin.id, targetType: "document", targetId: fixture.hiddenDoc })).effectiveNow).toBe(true);
  await expect(previewAccess(db, admin, { userId: staff.id, targetType: "document", targetId: crypto.randomUUID() })).rejects.toThrow();
  await db.update(userProfiles).set({ active: false }).where(eq(userProfiles.userId, staff.id));
  const inactivePreview = await previewAccess(db, admin, { userId: staff.id, targetType: "document", targetId: fixture.doc });
  expect(inactivePreview.effectiveNow).toBe(false);
  expect(inactivePreview.effectiveAfterTargetGrant).toBe(false);
  await db.update(userProfiles).set({ active: true }).where(eq(userProfiles.userId, staff.id));
  const hidden = await queryReport(db, staff, "search", { query: `Hidden secret ${code}` });
  expect(hidden.rows).toHaveLength(0);
  const visible = await queryReport(db, staff, "documents", { categoryId: fixture.category });
  expect(visible.rows.map((row) => row.id)).toEqual([fixture.doc]);
  const summary = await dashboard(db, staff);
  const viewerSummary = await dashboard(db, viewer);
  expect(summary.counts.documents).toBeGreaterThanOrEqual(1);
  expect(viewerSummary.operations).toBeNull();
  expect(viewerSummary.recent).toEqual([]);
  await expect(queryReport(db, viewer, "ledger", {})).rejects.toThrow();
  await expect(exportReport(db, viewer, "documents", {}, correlationId)).rejects.toThrow();
  for (const kind of reportKinds) await expect(queryReport(db, staff, kind, {})).resolves.toBeDefined();
  const firstPage = await queryReport(db, staff, "search", { categoryId: fixture.category }, 1, 1);
  const secondPage = await queryReport(db, staff, "search", { categoryId: fixture.category }, 2, 1);
  expect(firstPage.hasMore).toBe(true);
  expect(firstPage.rows[0]?.id).not.toBe(secondPage.rows[0]?.id);
  await expect(exportReport(db, staff, "documents", { categoryId: fixture.category }, undefined as unknown as string)).rejects.toThrow();
  const exported = await exportReport(db, staff, "documents", { categoryId: fixture.category }, correlationId);
  expect(exported.rowCount).toBe(1);
  expect(exported.csv).toContain("'=SUM(1,1)");
  expect(exported.csv).toContain('""quoted""');
  expect(exported.csv).not.toContain(`Hidden secret ${code}`);
  const audit = await db.select().from(auditLogs).where(eq(auditLogs.correlationId, correlationId));
  expect(audit.some((entry) => entry.action === "report.exported")).toBe(true);
  const grant = await grantAccess(db, admin, { userId: staff.id, boxId: fixture.hiddenBox, correlationId });
  expect((await previewAccess(db, admin, { userId: staff.id, targetType: "document", targetId: fixture.hiddenDoc })).effectiveNow).toBe(true);
  expect((await queryReport(db, staff, "search", { query: `Hidden secret ${code}` })).rows).toHaveLength(1);
  expect((await queryReport(db, staff, "documents", { query: `Hidden secret ${code}`, confidentiality: "restricted" })).rows).toHaveLength(1);
  expect((await dashboard(db, staff)).counts.documents).toBe(summary.counts.documents + 1);
  await db.update(folders).set({ confidentiality: "restricted" }).where(eq(folders.id, fixture.hiddenFolder));
  expect((await queryReport(db, staff, "search", { query: `Hidden secret ${code}` })).rows).toHaveLength(0);
  const folderPreview = await previewAccess(db, admin, { userId: staff.id, targetType: "folder", targetId: fixture.hiddenFolder });
  expect(folderPreview.effectiveAfterTargetGrant).toBe(true);
  expect(folderPreview.missing.map((level) => level.id)).toEqual([fixture.hiddenFolder]);
  const childGrant = await grantAccess(db, admin, { userId: staff.id, folderId: fixture.hiddenFolder, correlationId });
  expect((await queryReport(db, staff, "search", { query: `Hidden secret ${code}` })).rows).toHaveLength(1);
  await revokeAccess(db, admin, { grantId: childGrant.id, correlationId });
  await revokeAccess(db, admin, { grantId: grant.id, correlationId });
  expect((await queryReport(db, staff, "search", { query: `Hidden secret ${code}` })).rows).toHaveLength(0);
  expect((await dashboard(db, staff)).counts.documents).toBe(summary.counts.documents);
  await db.update(documents).set({ confidentiality: "restricted" }).where(eq(documents.id, fixture.hiddenDoc));
  const independent = await previewAccess(db, admin, { userId: staff.id, targetType: "document", targetId: fixture.hiddenDoc });
  expect(independent.missing.map((level) => level.id)).toEqual([fixture.hiddenBox, fixture.hiddenFolder, fixture.hiddenDoc]);
  expect(independent.effectiveAfterTargetGrant).toBe(false);
  const parentOnly = await previewAccess(db, admin, { userId: staff.id, targetType: "folder", targetId: fixture.hiddenFolder });
  expect(parentOnly.path.some((level) => level.id === fixture.hiddenDoc)).toBe(false);
  await db.update(documents).set({ confidentiality: "internal" }).where(eq(documents.id, fixture.hiddenDoc));

  expect((await auditFilterChoices(db, admin)).actions).toContain("report.exported");
  for (let i = 0; i < 4; i++) await exportReport(db, staff, "documents", { categoryId: fixture.category }, correlationId);
  await expect(exportReport(db, staff, "documents", { categoryId: fixture.category }, correlationId)).rejects.toThrow("Too many exports");
});
