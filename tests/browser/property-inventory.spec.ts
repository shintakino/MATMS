import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { readFile } from "node:fs/promises";
import * as XLSX from "../../packages/api/node_modules/xlsx/xlsx.mjs";

const email = process.env.MATMS_BROWSER_EMAIL;
const password = process.env.MATMS_BROWSER_PASSWORD;
test.skip(!email || !password, "Supply disposable browser-test credentials.");

test("property inventory opening and stock-card workflow", async ({ page }) => {
  page.setDefaultTimeout(90_000);
  page.setDefaultNavigationTimeout(90_000);
  const browserErrors: string[] = [];
  page.on("pageerror", (error) => browserErrors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("Email address").fill(email!);
  await page.getByLabel("Password", { exact: true }).fill(password!);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto("/property-inventory/counts");
  const profile = page.locator("details").filter({ has: page.getByText("Record approved form profile", { exact: true }) });
  await profile.locator(":scope > summary").click();
  await profile.getByLabel("Form family").selectOption("stock_card");
  await profile.getByRole("button", { name: "Load reference starting point" }).click();
  const definitionInput = profile.getByLabel("Reviewed layout definition (JSON)");
  const definition = JSON.parse(await definitionInput.inputValue());
  definition.sheets[0].stockCardPageRows = 3;
  await definitionInput.fill(JSON.stringify(definition));
  await profile.getByLabel("Effective date").fill("2026-01-01");
  await profile.getByLabel("Version note").fill("Fictional Stock Card browser test");
  await profile.getByLabel("School visual approval reference").fill("Fictional browser fixture; not an approval");
  await profile.getByRole("button", { name: "Record profile version" }).click();
  await expect(profile.getByText("Form profile version recorded.")).toBeVisible();
  await page.goto("/property-inventory");
  await expect(page.getByRole("heading", { name: "Property inventory", exact: true })).toBeVisible();
  const code = `BROWSER-${crypto.randomUUID()}`;
  const reference = "Verified browser reference ".repeat(20).trim();
  const create = page.locator("details").filter({ has: page.getByText("Create item", { exact: true }) });
  await create.locator(":scope > summary").click();
  await create.getByLabel("Item / stock code").fill(code);
  await create.getByLabel("Article", { exact: true }).fill("Fictional test supplies");
  await create.getByLabel("Description").fill("Browser verification only");
  await create.getByLabel("Unit of measure").fill("box");
  await create.getByText("Optional stock and report settings", { exact: true }).click();
  await create.getByLabel("Reorder point (optional)").fill("5");
  await create.getByRole("button", { name: "Create item", exact: true }).click();
  await expect(page.getByText("Item created. Open it to add a lot or office balance.")).toBeVisible();
  await expect(page.getByRole("link", { name: "Continue item setup" })).toBeVisible();
  const filters = page.locator("details").filter({ has: page.getByText("Search and filters", { exact: true }) });
  await filters.locator(":scope > summary").click();
  await filters.getByLabel("Search", { exact: true }).fill(code);
  await filters.getByRole("button", { name: "Apply filters" }).click();
  await page.getByRole("link", { name: "Fictional test supplies" }).click();
  const itemPath = new URL(page.url()).pathname;
  await expect(page.getByRole("region", { name: "Set up this item" })).toBeVisible();
  await page.getByRole("button", { name: "Go to next step" }).click();
  await expect(page.locator("#setup-balance")).toHaveAttribute("open", "");
  const addBalance = page.locator("details").filter({ has: page.getByText("Create office balance", { exact: true }) });
  // The guided next-step action already opened this section.
  await addBalance.getByLabel("Fund cluster").fill("BROWSER");
  await addBalance.getByLabel("Office / location").fill("Fictional office");
  await addBalance.getByRole("button", { name: "Create zero balance" }).click();
  await expect(page.getByText("Office balance created with zero stock.")).toBeVisible();
  const operation = page.locator("details").filter({ has: page.getByText("Record stock operation", { exact: true }) });
  await operation.locator(":scope > summary").click();
  await operation.getByRole("combobox", { name: "Action", exact: true }).selectOption("transfer");
  await expect(operation.getByLabel("Transfer destination")).toBeVisible();
  await operation.getByRole("combobox", { name: "Action", exact: true }).selectOption("issue");
  await expect(operation.getByLabel("Transfer destination")).toHaveCount(0);
  await expect(operation.getByLabel("Days to consume (issue only)")).toBeVisible();
  await operation.getByRole("combobox", { name: "Action", exact: true }).selectOption("opening");
  await expect(operation.getByLabel("Days to consume (issue only)")).toHaveCount(0);
  await operation.getByRole("combobox", { name: "Balance", exact: true }).selectOption({ index: 1 });
  await operation.getByLabel("Quantity (new count for correction)").fill("10");
  await operation.getByLabel("Transaction date").fill("2026-01-01");
  await operation.getByLabel("Reference", { exact: true }).fill(reference);
  await operation.getByLabel("Reason / purpose").fill("Fictional opening");
  await operation.getByRole("button", { name: "Review operation" }).click();
  await expect(page.getByRole("alertdialog")).toContainText("Fictional office: 0 → 10");
  await page.getByRole("alertdialog").getByRole("button", { name: "Confirm operation" }).click();
  await expect(page.getByText("Stock operation recorded.")).toBeVisible();
  const editItem = page.locator("details").filter({ has: page.getByText("Edit item", { exact: true }) });
  await editItem.locator(":scope > summary").click();
  await editItem.getByLabel("Description", { exact: true }).fill("Updated fictional description");
  await editItem.getByLabel("Reason for change").fill("Browser metadata correction");
  await editItem.getByRole("button", { name: "Review item changes" }).click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Confirm changes" }).click();
  await expect(page.getByText("Item details updated.")).toBeVisible();
  const addLot = page.locator("details").filter({ has: page.getByText("Create lot", { exact: true }) });
  await addLot.locator(":scope > summary").click();
  await expect(addLot.getByLabel("Supplier / source")).toBeHidden();
  const optional = addLot.locator("details").filter({ has: page.getByText("Optional acquisition details", { exact: true }) });
  await optional.locator(":scope > summary").click();
  await addLot.getByLabel("Supplier / source").fill("Fictional supplier");
  await optional.locator(":scope > summary").click();
  await optional.locator(":scope > summary").click();
  await expect(addLot.getByLabel("Supplier / source")).toHaveValue("Fictional supplier");
  await addLot.getByLabel("Class").selectOption("ppe");
  await addLot.getByLabel("Property number").fill(code);
  await addLot.getByLabel("Unit value in PHP (blank if unknown)").fill("0");
  await addLot.getByLabel("Fund cluster").fill("BROWSER");
  await addLot.getByLabel("Office / location").fill("Fictional office");
  await addLot.getByRole("button", { name: "Create lot", exact: true }).click();
  await expect(page.getByText("Lot created.")).toBeVisible();
  const editLot = page.locator("details").filter({ has: page.getByText("Edit lot", { exact: true }) });
  await editLot.locator(":scope > summary").click();
  await editLot.getByLabel("Unit value in PHP (blank if unknown)").fill("5.00");
  await editLot.getByLabel("Reason for change").fill("Correct fictional valuation");
  await editLot.getByRole("button", { name: "Review lot changes" }).click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Confirm changes" }).click();
  await expect(editLot.getByText("Lot details updated.")).toBeVisible();
  await page.getByRole("link", { name: "View stock card" }).click();
  await page.getByLabel("Fund cluster").fill("BROWSER");
  await page.getByLabel("As of").fill("2026-01-01");
  await page.getByRole("button", { name: "Show stock card" }).click();
  await expect(page.getByText(reference, { exact: true })).toBeVisible();
  await expect(page.getByText(/Balance 10 box/)).toBeVisible();
  await page.getByLabel("Entity / school").fill("Fictional school");
  await page.getByLabel("Stock Card profile").selectOption({ index: 1 });
  await page.getByRole("button", { name: "Review report scope" }).click();
  await page.getByRole("button", { name: "Generate Excel workbook" }).click();
  await expect(page.getByText("Workbook generated and saved to report history.")).toBeVisible();
  const download = page.waitForEvent("download");
  await page.getByRole("link", { name: /Download .*\.xlsx/ }).click();
  const file = await readFile((await (await download).path())!);
  const sheet = XLSX.read(file, { type: "buffer" }).Sheets.SC!;
  let joined = "", carryCount = 0;
  for (let row = 13; row <= XLSX.utils.decode_range(sheet["!ref"]!).e.r + 1; row++) {
    if (sheet[`B${row}`]?.v === "Balance brought forward") { expect(sheet[`F${row}`]?.v).toBe(10); carryCount++; }
    else joined += sheet[`B${row}`]?.v ?? "";
  }
  expect(joined).toBe(reference);
  expect(carryCount).toBeGreaterThan(0);
  await page.getByRole("link", { name: "Preview and print" }).click();
  await expect(page.locator("#inventory-print .form-page").first()).toBeVisible();
  await expect(page.locator("#inventory-print").getByText("Balance brought forward").first()).toBeVisible();
  const previewReference = await page.locator("#inventory-print tbody tr").evaluateAll((rows) => rows.map((row) => row.children[1]?.textContent ?? "").filter((value) => value !== "Balance brought forward").join(""));
  expect(previewReference).toBe(reference);
  for (const path of ["/property-inventory", itemPath]) {
    await page.goto(path);
    const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze();
    expect(accessibility.violations, `${path}: ${accessibility.violations.map((entry) => entry.id).join(", ")}`).toEqual([]);
  }
  expect(browserErrors).toEqual([]);
});
