import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { readFile } from "node:fs/promises";
import * as XLSX from "../../packages/api/node_modules/xlsx/xlsx.mjs";

const email = process.env.MATMS_BROWSER_EMAIL;
const password = process.env.MATMS_BROWSER_PASSWORD;
test.skip(!email || !password, "Supply disposable browser-test credentials.");

test("create, review and finalize a mixed-condition partial count", async ({ page }) => {
  page.setDefaultTimeout(90_000); page.setDefaultNavigationTimeout(90_000);
  await page.goto("/login"); await page.getByLabel("Email address").fill(email!); await page.getByLabel("Password", { exact: true }).fill(password!); await page.getByRole("button", { name: "Sign in", exact: true }).click(); await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto("/property-inventory/counts");
  const profile = page.locator("details").filter({ has: page.getByText("Record approved form profile", { exact: true }) });
  await profile.locator(":scope > summary").click();
  await profile.getByLabel("Form family").selectOption("rpcppe");
  await profile.getByRole("button", { name: "Load reference starting point" }).click();
  await profile.getByLabel("Effective date").fill("2026-01-01");
  await profile.getByLabel("Version note").fill("Fictional browser test only");
  await profile.getByLabel("Default Property Custodian", { exact: true }).fill("Fictional default custodian");
  await profile.getByLabel("School visual approval reference").fill("Fictional browser fixture; not an approval");
  await profile.getByRole("button", { name: "Record profile version" }).click();
  await expect(profile.getByText("Form profile version recorded.")).toBeVisible();
  const fund = `BROWSER-${crypto.randomUUID()}`;
  const itemCode = `COUNT-ITEM-${crypto.randomUUID()}`;
  const description = "Fictional long description ".repeat(25);
  await page.goto("/property-inventory");
  const item = page.locator("details").filter({ has: page.getByText("Create item", { exact: true }) });
  await item.locator(":scope > summary").click();
  await item.getByLabel("Item / stock code").fill(itemCode);
  await item.getByLabel("Article", { exact: true }).fill("Fictional count item");
  await item.getByLabel("Description").fill(description);
  await item.getByLabel("Unit of measure").fill("piece");
  await item.getByText("Optional stock and report settings", { exact: true }).click();
  await item.getByLabel("Default report section").selectOption({ label: "LAND (SCHOOL SITE)" });
  await item.getByRole("button", { name: "Create item", exact: true }).click();
  await expect(page.getByText("Item created. Open it to add a lot or office balance.")).toBeVisible();
  const filters = page.locator("details").filter({ has: page.getByText("Search and filters", { exact: true }) });
  await filters.locator(":scope > summary").click();
  await filters.getByLabel("Search", { exact: true }).fill(itemCode);
  await filters.getByRole("button", { name: "Apply filters" }).click();
  await page.getByRole("link", { name: "Fictional count item", exact: true }).click();
  const lot = page.locator("details").filter({ has: page.getByText("Create lot", { exact: true }) });
  await lot.locator(":scope > summary").click();
  await lot.getByLabel("Class").selectOption("ppe");
  await lot.getByLabel("Property number").fill(itemCode);
  await lot.getByLabel("Unit value in PHP (blank if unknown)").fill("10.00");
  await lot.getByLabel("Fund cluster").fill(fund);
  await lot.getByLabel("Office / location").fill("Fictional office");
  await lot.getByRole("button", { name: "Create lot", exact: true }).click();
  await expect(page.getByText("Lot created.")).toBeVisible();
  await page.goto("/property-inventory/counts");
  const create = page.locator("details").filter({ has: page.getByText("Create count session", { exact: true }) });
  await create.locator(":scope > summary").click();
  const code = `COUNT-${crypto.randomUUID()}`;
  await create.getByLabel("Session code").fill(code);
  await create.getByLabel("Form family").selectOption("rpcppe");
  await create.getByLabel("Form profile").selectOption({ index: 1 });
  await create.getByRole("button", { name: "Apply profile signatories" }).click();
  await expect(create.getByLabel("Property Custodian", { exact: true })).toHaveValue("Fictional default custodian");
  await create.getByLabel("As of").fill("2026-01-01");
  await create.getByLabel("LAND (SCHOOL SITE) · RPCPPE_LAND").check();
  await create.getByLabel("Fund cluster").fill(fund);
  for (const label of ["Entity / school", "Accountable officer", "Accountable officer designation", "Property Custodian", "Property Custodian designation", "Committee chair", "Committee chair designation", "Committee member", "Committee member designation", "School Head", "School Head designation"]) await create.getByLabel(label, { exact: true }).fill(`Test ${label}`);
  await create.getByLabel("Accountability assumed date").fill("2026-01-01");
  await create.getByRole("button", { name: "Create count session", exact: true }).click();
  await expect(page.getByText("Count session created.")).toBeVisible();
  await page.getByRole("link", { name: code, exact: true }).click();
  await expect(page.getByRole("heading", { name: code, exact: true })).toBeVisible();
  const line = page.locator("article").filter({ has: page.getByRole("heading", { name: new RegExp(itemCode) }) });
  await expect(line).toBeVisible();
  await line.getByLabel("Physical quantity").fill("8");
  await line.getByRole("combobox", { name: "Condition", exact: true }).selectOption("mixed");
  await line.getByLabel("serviceable", { exact: true }).fill("5");
  await line.getByLabel("unserviceable", { exact: true }).fill("3");
  await line.getByRole("button", { name: "Save count" }).click();
  await expect(page.getByText("Physical count saved.")).toBeVisible();
  await expect(page.getByText(/All sections · piece.*Card 0.*Physical 8.*Overage 8/)).toBeVisible();
  await expect(page.getByText(/Known overage value: ₱80.00/)).toBeVisible();
  await line.getByLabel("Review note", { exact: true }).fill("Reviewed mixed condition");
  await line.getByRole("button", { name: "Record review" }).click();
  await expect(page.getByText("Review note saved.")).toBeVisible();
  await expect(page.getByText(/Partial count: 1 selected section/)).toBeVisible();
  await page.getByRole("button", { name: "Preview changes" }).click();
  await expect(page.getByText("0 changed lines · 0 unavailable lines")).toBeVisible();
  for (const sheet of ["RPCPPE_LAND", "RPCPPE_BLDG", "RPCPPE_OTHERBLDG"]) await page.getByLabel(`Reviewed ${sheet}`).check();
  await expect(page.getByRole("region", { name: "Count progress" })).toBeVisible();
  await page.getByRole("button", { name: "Review finalization" }).click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Finalize count" }).click();
  await expect(page.getByText("Count finalized. Its report data is now frozen.")).toBeVisible();
  await page.getByRole("button", { name: "Review report scope" }).click();
  await page.getByRole("button", { name: "Generate Excel workbook" }).click();
  await expect(page.getByText("Workbook generated and saved to report history.")).toBeVisible();
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("link", { name: /Download .*\.xlsx/ }).click();
  const downloaded = await downloadEvent;
  const file = await readFile((await downloaded.path())!);
  const workbook = XLSX.read(file, { type: "buffer" });
  expect(workbook.SheetNames).toEqual(["RPCPPE_LAND", "RPCPPE_BLDG", "RPCPPE_OTHERBLDG"]);
  expect(workbook.Sheets.RPCPPE_LAND?.L14?.v).toContain("serviceable: 5, unserviceable: 3");
  const sheet = workbook.Sheets.RPCPPE_LAND!;
  let row = 14, joinedDescription = "";
  while (sheet[`A${row}`]?.v !== "GRAND TOTAL" && row < 100) { joinedDescription += sheet[`B${row}`]?.v ?? ""; row++; }
  expect(row).toBeGreaterThan(15);
  expect(joinedDescription).toBe(description.trim());
  const countPath = new URL(page.url()).pathname;
  await page.getByRole("link", { name: "Preview and print" }).click();
  await expect(page.locator("#inventory-print .form-page")).toHaveCount(3);
  await expect(page.locator("#inventory-print").getByText("As of January 2026")).toHaveCount(3);
  await expect(page.locator("#inventory-print").getByText("Signature over Printed Name of School Inventory")).toHaveCount(6);
  await expect(page.locator("#inventory-print").getByText("USE RPCPPE FORM FOR 50K UP")).toHaveCount(3);
  await expect(page.locator("#inventory-print").getByText("(e.g  School Building, Land etc)")).toHaveCount(3);
  await expect(page.locator("#inventory-print").getByText(/Partial count — selected sections/)).toHaveCount(3);
  await page.emulateMedia({ media: "print" });
  await expect(page.getByRole("link", { name: "Report history" })).toBeHidden();
  expect((await page.pdf({ format: "A4", landscape: true, printBackground: true })).length).toBeGreaterThan(1000);
  await page.emulateMedia({ media: "screen" });
  await page.goto(countPath);
  const amend = page.locator("details").filter({ has: page.getByText("Create linked amendment", { exact: true }) });
  await amend.locator(":scope > summary").click();
  await amend.getByLabel("Amendment code").fill(`${code}-A`);
  await amend.getByLabel("Reason").fill("Fictional test correction");
  await amend.getByRole("button", { name: "Create amendment" }).click();
  await expect(page.getByText("Amendment created. Open it from the count list.")).toBeVisible();
  const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze();
  expect(accessibility.violations.map((entry) => entry.id)).toEqual([]);
});
